"""Generate the README datasets table from the bundled manifests.

    python docs/_gen/datasets_table.py            # prints Markdown to stdout

Every cell comes from the manifest: no number is typed by hand. Size is the
manifest's ``size_mb`` (the whole source, not what one sample costs to fetch).
"""

from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlparse

MANIFESTS = Path(__file__).resolve().parents[2] / "src" / "pardesline" / "data" / "manifests"
DOCS = "https://pardesline.github.io/pardesline/latest/datasets"

MODALITY_TAGS = {
    "ct": "CT",
    "mri": "MRI",
    "mr": "MRI",
    "pet": "PET",
    "ultrasound": "US",
    "microscopy": "microscopy",
    "dicom": "DICOM",
    "nifti": "NIfTI",
    "metaimage": "MetaImage",
    "lidar": "LiDAR",
    "points": "points",
    "mesh": "mesh",
    "stl": "STL",
    "splat": "Gaussian splats",
    "stereo": "stereo",
    "endoscopy": "endoscopy",
    "4d": "4D",
}


def host(m: dict) -> str:
    src = m["source"]
    scheme = src["scheme"]
    if scheme == "hf":
        return f"Hugging Face `{src['repo_id']}`"
    if scheme == "tcia":
        return f"TCIA `{src['collection']}`"
    if scheme == "s3":
        return f"S3 `{src['bucket']}`"
    if scheme == "open3d":
        return "Open3D data"
    url = src.get("url") or (src.get("urls") or [None])[0] or src.get("index_url") or m.get("homepage") or ""
    if not url and src.get("files"):
        url = next(iter(src["files"].values())).get("url") or m.get("homepage") or ""
    return urlparse(url).netloc.replace("www.", "") or scheme


def size(m: dict) -> str:
    mb = m.get("size_mb")
    if mb is None:
        return ""
    return f"{mb / 1024:.1f} GB" if mb >= 1024 else f"{mb:g} MB"


def licence(m: dict) -> str:
    lic = m.get("license", {})
    spdx = lic.get("spdx")
    if not spdx:
        return "see source"
    out = spdx
    if lic.get("requires_agreement"):
        out += " (gated)"
    return out


def modality(m: dict) -> str:
    tags = m.get("tags", [])
    seen: list[str] = []
    for t in tags:
        label = MODALITY_TAGS.get(t)
        if label and label not in seen:
            seen.append(label)
    kinds = sorted({r["type"] for r in m["roles"].values()})
    kind_label = ", ".join(
        k for k in kinds if k in ("volume", "labels", "mesh", "points", "splat", "image", "array")
    )
    return (" / ".join(seen[:3]) + (f" ({kind_label})" if kind_label else "")).strip()


def row(m: dict) -> str:
    name = m["name"]
    title = m.get("title") or name
    return (
        f"| [{title}]({DOCS}/{name}/) | {modality(m)} | {size(m)} | {licence(m)} | "
        f'{host(m)} | `pl.load("{name}")` |'
    )


def main() -> None:
    manifests = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(MANIFESTS.glob("*.json"))]
    medical = [m for m in manifests if "medical" in m.get("tags", [])]
    general = [m for m in manifests if "medical" not in m.get("tags", [])]
    header = (
        "| Dataset | Modality / type | Size | Licence | Source | One-line loader |\n|---|---|---|---|---|---|"
    )
    print(f"**Medical ({len(medical)})**\n")
    print(header)
    for m in medical:
        print(row(m))
    print(f"\n**General 3D ({len(general)})**\n")
    print(header)
    for m in general:
        print(row(m))
    print(f"\n<!-- generated by docs/_gen/datasets_table.py from {len(manifests)} manifests -->")


if __name__ == "__main__":
    main()
