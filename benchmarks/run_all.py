"""Run every benchmark and write benchmarks/results.md (included by docs/benchmarks.md).

    python benchmarks/run_all.py

The tables are generated, never typed: each script prints its Markdown table
and stores the raw numbers under benchmarks/results/*.json. The command that
produced each table and the date are written above it.
"""

from __future__ import annotations

import datetime as _dt
import platform
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
SCRIPTS = [
    (
        "Rigid point-cloud registration on the Stanford bunny (35 deg, 70 % overlap, 0.5 % noise)",
        "registration_bunny.py",
        ["--trials", "5"],
    ),
    (
        "Poisson surface reconstruction on a partial, noisy bunny scan",
        "reconstruction_bunny.py",
        ["--trials", "3"],
    ),
]


def main() -> None:
    import pardesline

    out = [
        f"<!-- generated by benchmarks/run_all.py on {_dt.date.today().isoformat()}; do not edit -->",
        "",
        f"pardesline {pardesline.__version__}, Python {platform.python_version()}, {platform.system()} {platform.machine()}, CPU only.",
        "",
    ]
    for title, script, extra in SCRIPTS:
        cmd = [sys.executable, str(HERE / script), *extra]
        print("$", " ".join(cmd[1:]), flush=True)
        res = subprocess.run(cmd, check=True, capture_output=True, text=True)
        table = "\n".join(line for line in res.stdout.splitlines() if line.startswith("|"))
        out += [f"### {title}", "", f"`python benchmarks/{script} {' '.join(extra)}`", "", table, ""]
    (HERE / "results.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", HERE / "results.md")


if __name__ == "__main__":
    main()
